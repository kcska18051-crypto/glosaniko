def read(path):
    return path.read_text(encoding='utf-8')


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8')


def article(key):
    title, description, content = ARTICLES[key]
    return (f'<main id="main"><section class="collection-hero simple-hero legal-hero"><div class="wrap">'
            f'<nav class="breadcrumbs" aria-label="Хлебные крошки"><a href="../">Главная</a>'
            f'<span aria-hidden="true">/</span><span aria-current="page">{title}</span></nav>'
            f'<h1>{title}</h1></div></section><section class="collection-section legal-section">'
            f'<article class="wrap legal-copy"><p class="legal-summary">{description}</p>{content}'
            f'</article></section></main>')


def update_page(key, source):
    title, description, _ = ARTICLES[key]
    source = re.sub(r'<title>.*?</title>', f'<title>{title} — Glosaniko</title>', source, count=1)
    source = re.sub(r'<meta name="description" content="[^"]*">',
                    f'<meta name="description" content="{SEO_DESCRIPTIONS.get(key, description)}">', source, count=1)
    source = re.sub(r'<main id="main">.*?</main>', article(key), source, count=1, flags=re.S)
    if '../pages.css' not in source:
        source = source.replace('<link rel="stylesheet" href="../privacy-ui.css',
                                '<link rel="stylesheet" href="../pages.css?v=1"><link rel="stylesheet" href="../privacy-ui.css', 1)
    if '../legal-articles.css' not in source:
        source = source.replace('</head>', '<link rel="stylesheet" href="../legal-articles.css?v=1"></head>', 1)
    return source


def main():
    privacy_source = read(ROOT / 'privacy/index.html')
    for key in ARTICLES:
        path = ROOT / key / 'index.html'
        source = read(path) if path.exists() else privacy_source
        write(path, update_page(key, source))

    # Link the document from the legal articles and pages with active forms.
    for relative in ['index.html', 'contacts/index.html', 'dealers/index.html',
                     'privacy/index.html', 'consent/index.html', 'terms/index.html']:
        path = ROOT / relative
        source = read(path)
        if '<h2>Документы</h2>' not in source:
            continue
        match = re.search(r'<a href="([./]+)consent/">Согласие на обработку персональных данных</a>', source)
        if not match:
            raise ValueError(f'Unexpected footer path: {path}')
        old = match.group(0)
        new = old + f'<a href="{match.group(1)}terms/">Пользовательское соглашение</a>'
        if 'Пользовательское соглашение</a>' not in source:
            source = source.replace(old, new, 1)
            write(path, source)

    # Keep the privacy acknowledgement distinct from the consent checkbox.
    for relative in ['index.html', 'concept.html', 'contacts/index.html', 'dealers/index.html']:
        path = ROOT / relative
        source = read(path)
        prefix = './' if '/' not in relative else '../'
        old = (f'Ознакомлен(а) с <a href="{prefix}privacy/" target="_blank" '
               f'rel="noopener">политикой конфиденциальности</a>')
        new = (old + f' и принимаю <a href="{prefix}terms/" target="_blank" '
               f'rel="noopener">пользовательское соглашение</a>')
        if old not in source:
            raise ValueError(f'Consent text missing: {path}')
        if 'пользовательское соглашение</a>' not in source.split('class="form-consents"', 1)[1].split('</div>', 1)[0]:
            write(path, source.replace(old, new, 1))

    server_path = ROOT / 'server.mjs'
